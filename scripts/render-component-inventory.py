#!/usr/bin/env python3
"""Render declared Cargo edges/features and textual include ownership, without building."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def inventory():
    workspace = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]
    members = {}
    for relative in workspace["members"]:
        path = ROOT / relative / "Cargo.toml"
        value = tomllib.loads(path.read_text())
        members[value["package"]["name"]] = (relative, value)
    result = {"schema_version": 1, "components": {}, "includes": []}
    for name, (relative, value) in sorted(members.items()):
        edges = []
        scopes = [("all", value), *sorted(value.get("target", {}).items())]
        for target, scope in scopes:
            for kind in ("dependencies", "dev-dependencies", "build-dependencies"):
                for alias, entry in sorted(scope.get(kind, {}).items()):
                    entry = entry if isinstance(entry, dict) else {"version": entry}
                    package = entry.get("package", alias)
                    if package in members:
                        edges.append({"package": package, "alias": alias, "kind": kind,
                                      "target": target, "optional": entry.get("optional", False),
                                      "default_features": entry.get("default-features", True),
                                      "features": entry.get("features", [])})
        result["components"][name] = {"path": relative, "dependencies": edges,
                                      "features": value.get("features", {}),
                                      "build_script": (relative + "/" + value.get("package", {}).get("build", "build.rs"))
                                      if (ROOT / relative / value.get("package", {}).get("build", "build.rs")).is_file() else None}
    files = subprocess.check_output(["git", "-C", str(ROOT), "ls-files", "-z", "crates"])
    for raw in files.split(b"\0"):
        if not raw or not raw.endswith(b".rs"):
            continue
        relative = raw.decode()
        for number, line in enumerate((ROOT / relative).read_text().splitlines(), 1):
            for match in re.finditer(r"\b(include(?:_str|_bytes)?)!\s*\((.*)", line):
                result["includes"].append({"source": relative, "line": number,
                                           "macro": match.group(1), "expression": match.group(2).strip()})
    return result


def markdown(value):
    lines = ["# Component inventory", "", "Generated by `python3 scripts/render-component-inventory.py`; verify with `--check`.", "",
             "This inventory records declared workspace dependencies, feature expansions, build scripts, and textual include sites. It does not evaluate cfg expressions or infer arbitrary build-script file reads. Use the conservative workspace/feature CI fallback when impact is uncertain.", "",
             "| Component | Internal dependency edges | Build script |", "| --- | --- | --- |"]
    for name, component in value["components"].items():
        edges = sorted({entry["package"] + (" (" + entry["kind"] + ")" if entry["kind"] != "dependencies" else "")
                        for entry in component["dependencies"]})
        lines.append("| " + name + " | " + ", ".join(edges) + " | " + (component["build_script"] or "—") + " |")
    lines += ["", "## Features", "", "Exact target conditions, optional/default dependency feature flags, and textual include locations are in [component-inventory.json](component-inventory.json).", "",
              "| Component | Feature | Expands to |", "| --- | --- | --- |"]
    for name, component in value["components"].items():
        for feature, expansion in component["features"].items():
            lines.append("| " + name + " | " + feature + " | " + ", ".join(expansion) + " |")
    lines += ["", "## Ownership", "",
              "- Shared contracts: `oryn-common`, `oryn-core`.",
              "- Document and platform primitives: `oryn-dom`, `oryn-net`, `oryn-webidl`.",
              "- Presentation: `oryn-layout`, `oryn-render-core`, `oryn-render`.",
              "- JavaScript and native runtime: `oryn-js`, `oryn-native`.",
              "- Backend orchestration: `oryn-engine`, `oryn-h`, `oryn-e`, `oryn-r`, `oryn-scanner`.",
              "- Product integration: `oryn-domain`, `oryn`.", "",
              "This is an ownership grouping, not a claim of strict dependency layering. Review textual includes with their parent compilation unit. Keep runtime module reorganization separate from this workflow migration.", "",
              "The scanner's canonical JavaScript is `crates/oryn-scanner/src/scanner.js`; `scripts/sync-scanner.sh` generates extension copies. WebIDL inputs/generator stay in `oryn-webidl`. Native V8 patches, generated bindings, startup snapshot/external references, and ICU inputs remain explicit source/build dependencies; generated cache contents are not implicitly admitted because a build succeeded.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = inventory()
    files = {"component-inventory.json": json.dumps(value, indent=2, sort_keys=True) + "\n",
             "COMPONENTS.md": markdown(value)}
    for name, text in files.items():
        path = ROOT / "docs/development" / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit("component inventory stale: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
